"""Compute teaching agenda and exercise safe references. Writes only teaching/."""
import csv
import hashlib
import importlib.util
import json
import platform
import re
import subprocess
import sys
import tempfile
from html.parser import HTMLParser
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent


def load(name, subdir='labs'):
    spec = importlib.util.spec_from_file_location(name, ROOT / subdir / f'{name}.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def event(id_, stamp, result='success', user='training-user', country='US'):
    return dict(event_id=id_, user=user, timestamp_utc=f'2026-10-26T{stamp}Z',
                result=result, country=country)


def run(*args, expected=0):
    result = subprocess.run([sys.executable, *map(str, args)], capture_output=True,
                            text=True, timeout=15)
    assert (result.returncode == 0) == (expected == 0), result.stderr
    return {'command': ['python3', *[str(a).replace(str(ROOT), 'teaching') for a in args]],
            'exit_code': result.returncode,
            'stdout': result.stdout.strip(), 'stderr': result.stderr.strip()}


def main():
    agenda = json.loads((ROOT / 'agenda.json').read_text())
    assert [row['slide'] for row in agenda] == list(range(1, 22))
    assert all(isinstance(row['minutes'], int) and row['minutes'] > 0 for row in agenda)
    assert sum(row['minutes'] for row in agenda) == 120
    narrative = (ROOT / 'SLIDE-NARRATIVE.md').read_text()
    headings = re.findall(r'^## Slide (\d+) \| (\d+)–(\d+) \| (.+)$', narrative, re.M)
    assert len(headings) == len(agenda)
    lines = ['# Computed 120-minute agenda', '',
             'Round 2 teaching revision. Generated by `validate_teaching.py` from `agenda.json`.', '',
             '| Elapsed minutes | Minutes | Slide | Activity |',
             '| --- | ---: | --- | --- |']
    cursor = 0
    for row, heading in zip(agenda, headings):
        end = cursor + row['minutes']
        assert tuple(map(int, heading[:3])) == (row['slide'], cursor, end), heading
        assert heading[3] == row['title'], heading
        lines.append(f"| {cursor:02d}–{end:02d} | {row['minutes']} | {row['slide']}. {row['title']} | {row['activity']} |")
        cursor = end
    lines.extend(['', f'**Computed total: {cursor} minutes.** No overlapping or unallocated minutes.', '',
                  '20–25 is the capped five-minute readiness/recovery gate; 25–28 is evidence review and transition, not more setup. Troubleshooting stops at 25. Lab work, checkpoints and debriefs are explicitly included. Break is 48–53; Q&A is 115–120.', '',
                  'Time controls: route unresolved setup to review by minute 25; start lab 1 at 28. Stop log generation at 75 and app features at 105. Keep the checks, break and final Q&A. Optional stretches stay inside their work blocks or move after the session.', '',
                  'Run route practice: 10-minute checklist work + 18-minute script/code-review work + 3-minute reusable-instruction practice + 13-minute report build = 44 scheduled minutes, plus predictions, checkpoints and debriefs. Review route uses the same blocks.', ''])
    lines.extend(['Four optional support views in `projection-content.json` add zero minutes; display only inside their parent work blocks. They are not extra presentations.', ''])
    (ROOT / 'AGENDA.md').write_text('\n'.join(lines))
    fixture = ROOT / 'labs/signins.csv'
    before = hashlib.sha256(fixture.read_bytes()).hexdigest()
    triage = load('reference_triage').triage
    checker = load('check_triage')
    renderer = load('reference_report').render
    results = []
    checks = []
    projection = json.loads((ROOT/'projection-content.json').read_text())
    support = [row for row in projection if row['id'].startswith('S')]
    assert len(support) == 4 and len({row['id'] for row in projection}) == len(projection)
    for row in support:
        assert row['minutes'] == 0
        parent = row['parent_slide']
        start = sum(item['minutes'] for item in agenda[:parent-1])
        end = start + agenda[parent-1]['minutes']
        assert start <= row['display_window'][0] < row['display_window'][1] <= end
    for row in projection:
        if 'core_slide' in row:
            assert row['minutes'] == agenda[row['core_slide']-1]['minutes']
    packet = load('build_packet', '').build_packet()
    for path in ['offboarding-policy.txt', 'signins.csv', 'review-snippet.txt']:
        assert (ROOT/'labs'/path).read_text().strip() in packet
    assert packet.index('## A — facilitator reveal') > packet.index('## P4 — Monday')
    checks.extend(['zero-time support windows inside parent blocks', 'standalone packet embeds full source and delayed answers'])
    assert checker.check(ROOT/'labs/expected-events.csv').startswith('PASS')
    expected_rows = load('reference_report').read_rows(ROOT/'labs/expected-events.csv')
    (ROOT/'labs/expected-review.html').write_text(renderer(expected_rows))
    checks.append('supplied expected CSV independently checked and HTML generated')
    for stamp, expected in [('06:59:00', True), ('07:00:00', False),
                            ('18:59:59', False), ('19:00:00', True)]:
        assert bool(triage([event('S', stamp)])) == expected
        checks.append(f'hours boundary {stamp}')
    burst = [event('F1', '09:10:00', 'failure'), event('F2', '09:12:00', 'failure'),
             event('F3', '09:14:00', 'failure'), event('S', '09:20:00')]
    assert triage(burst)[0]['reasons'] == 'failure_burst'
    assert triage(list(reversed(burst))) == triage(burst)
    checks.extend(['inclusive ten-minute boundary', 'unsorted input'])
    expired = [{**row} for row in burst]
    expired[0]['timestamp_utc'] = '2026-10-26T09:09:59Z'
    assert triage(expired) == []
    other = [{**row, 'user': 'other'} if row['result'] == 'failure' else row for row in burst]
    assert triage(other) == []
    same_time = [event(f'F{i}', '09:20:00', 'failure') for i in range(3)] + [event('S', '09:20:00')]
    assert triage(same_time) == []
    future = [event(f'F{i}', '09:21:00', 'failure') for i in range(3)] + [event('S', '09:20:00')]
    assert triage(future) == []
    checks.extend(['expired window', 'same-user isolation', 'same-time exclusion', 'future exclusion'])
    multi = [event(f'F{i}', f'06:5{i}:00', 'failure') for i in range(3)] + [event('S', '06:59:00', country='CA')]
    assert set(triage(multi)[0]['reasons'].split(';')) == {'outside_hours', 'outside_baseline', 'failure_burst'}
    assert triage([event('F', '06:00:00', 'failure', country='CA')]) == []
    checks.extend(['multiple reasons', 'failures never output'])
    with tempfile.TemporaryDirectory(prefix='local-verification-', dir=ROOT) as folder:
        output = Path(folder) / 'events.csv'
        page = Path(folder) / 'report.html'
        results.append(run(ROOT/'labs/reference_triage.py', fixture, output))
        assert checker.check(output).startswith('PASS')
        results.append(run(ROOT/'labs/check_triage.py', output))
        results.append(run(ROOT/'labs/reference_triage.py', fixture, output, expected=1))
        results.append(run(ROOT/'labs/reference_triage.py', fixture, fixture, expected=1))
        results.append(run(ROOT/'labs/reference_report.py', output, page))
        content = page.read_text()
        assert '4 events for review; 3 reason categories.' in content
        assert content.count('<tbody>') == 1 and content.count('<tr>') == 5
        assert '0 events for review; 0 reason categories.' in renderer([])
        malicious = dict(event_id='X', user='<b>training</b>', timestamp_utc='training', reasons='outside_hours')
        safe = renderer([malicious])
        assert '&lt;b&gt;training&lt;/b&gt;' in safe and '<b>training</b>' not in safe
        tags = []
        class Inspect(HTMLParser):
            def handle_starttag(self, tag, attrs):
                tags.append(tag)
                assert not any(k in {'src', 'href'} or k.startswith('on') for k, v in attrs)
        Inspect().feed(safe)
        assert not {'script', 'img', 'iframe', 'b'} & set(tags)
        checks.extend(['HTML event/category counts', 'empty report', 'HTML escaping', 'no external asset attributes'])
        empty_page = Path(folder)/'empty.html'
        results.append(run(ROOT/'labs/reference_report.py', ROOT/'labs/report-empty.csv', empty_page))
        assert '0 events for review; 0 reason categories.' in empty_page.read_text()
        markup_page = Path(folder)/'markup.html'
        results.append(run(ROOT/'labs/reference_report.py', ROOT/'labs/report-markup.csv', markup_page))
        assert '&lt;b&gt;training&lt;/b&gt;' in markup_page.read_text()
        rejected = Path(folder)/'rejected.html'
        results.append(run(ROOT/'labs/reference_report.py', ROOT/'labs/report-wrong-columns.csv', rejected, expected=1))
        assert not rejected.exists()
        broken = Path(folder)/'broken.csv'
        broken.write_text('event_id,user,timestamp_utc,reasons\nT01,training\n')
        results.append(run(ROOT/'labs/reference_report.py', broken, rejected, expected=1))
        assert not rejected.exists()
        checks.extend(['empty-input CLI', 'markup-input CLI', 'wrong-column rejection without output', 'short-row rejection without output'])
        # A wrong set with the right count must fail the independent checker.
        with output.open(newline='') as handle:
            rows = list(csv.DictReader(handle))
        rows[0]['event_id'] = 'E08'
        wrong = Path(folder) / 'wrong.csv'
        with wrong.open('w', newline='') as handle:
            writer = csv.DictWriter(handle, fieldnames=['event_id','user','timestamp_utc','reasons'])
            writer.writeheader(); writer.writerows(rows)
        results.append(run(ROOT/'labs/check_triage.py', wrong, expected=1))
        checks.append('checker rejects wrong four-event set')
    assert hashlib.sha256(fixture.read_bytes()).hexdigest() == before
    checks.append('input hash unchanged')
    design_result = subprocess.run([sys.executable, '-I', str(ROOT.parent/'design/check_tokens.py'),
                                   '--slides', str(ROOT/'projection-content.json')],
                                  capture_output=True, text=True, timeout=15)
    assert design_result.returncode == 0, design_result.stdout + design_result.stderr
    report = {'status': 'PASS', 'agenda_minutes': cursor, 'slides': len(agenda),
              'support_slides': len(support), 'support_additional_minutes': 0,
              'python': platform.python_version(), 'platform': platform.platform(),
              'fixture_sha256_before_and_after': before, 'checks': checks,
              'subprocess_evidence': results,
              'design_lint': {'exit_code': design_result.returncode, 'stdout': design_result.stdout.strip()},
              'not_tested': ['agent login/generation', 'Linux or WSL VM execution',
                             'native Windows', 'live browser rendering',
                             'participant-generated code', 'classroom timing rehearsal',
                             'PowerPoint integration/rendering', 'scanner implementation']}
    (ROOT/'verification.json').write_text(json.dumps(report, indent=2) + '\n')
    print(f'PASS: {cursor} minutes; {len(agenda)} matching narrative slides; {len(support)} zero-time support views; {len(checks)} local checks; {len(results)} CLI checks; design lint PASS')


if __name__ == '__main__':
    main()
